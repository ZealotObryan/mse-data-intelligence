"use client";

import { useMemo, useState } from "react";
import styles from "./FinancialStatementExplorer.module.css";

type Values = {
  revenue: string;
  operatingCosts: string;
  currentAssets: string;
  currentLiabilities: string;
  operatingCashFlow: string;
  investingCashFlow: string;
  financingCashFlow: string;
};

const initial: Values = {
  revenue: "100000000",
  operatingCosts: "72000000",
  currentAssets: "65000000",
  currentLiabilities: "40000000",
  operatingCashFlow: "18000000",
  investingCashFlow: "-9000000",
  financingCashFlow: "-3000000",
};

const fields: { key: keyof Values; label: string; group: string; help: string }[] = [
  { key: "revenue", label: "Revenue (MWK)", group: "Income statement", help: "Sales earned during the reporting period." },
  { key: "operatingCosts", label: "Operating costs (MWK)", group: "Income statement", help: "Illustrative operating expenses; excludes tax and finance costs." },
  { key: "currentAssets", label: "Current assets (MWK)", group: "Financial position", help: "Assets expected to be realised or used within the operating cycle." },
  { key: "currentLiabilities", label: "Current liabilities (MWK)", group: "Financial position", help: "Obligations due within the operating cycle." },
  { key: "operatingCashFlow", label: "Operating cash flow (MWK)", group: "Cash flow", help: "Net cash generated by operating activities." },
  { key: "investingCashFlow", label: "Investing cash flow (MWK)", group: "Cash flow", help: "Net cash from investing activities; can be negative." },
  { key: "financingCashFlow", label: "Financing cash flow (MWK)", group: "Cash flow", help: "Net cash from financing activities; can be negative." },
];

const money = (value: number) =>
  new Intl.NumberFormat("en-MW", { style: "currency", currency: "MWK", maximumFractionDigits: 0 }).format(value);

export default function FinancialStatementExplorer() {
  const [values, setValues] = useState<Values>(initial);
  const parsed = useMemo(() => Object.fromEntries(
    Object.entries(values).map(([key, value]) => [key, value.trim() === "" ? null : Number(value)])
  ) as Record<keyof Values, number | null>, [values]);

  const valid = Object.values(parsed).every((value) => value !== null && Number.isFinite(value) && Math.abs(value) <= 1e15);
  const metrics = useMemo(() => {
    if (!valid) return null;
    const revenue = parsed.revenue!;
    const operatingCosts = parsed.operatingCosts!;
    const assets = parsed.currentAssets!;
    const liabilities = parsed.currentLiabilities!;
    const profit = revenue - operatingCosts;
    return {
      illustrativeOperatingSurplus: profit,
      operatingMargin: revenue > 0 ? profit / revenue : null,
      workingCapital: assets - liabilities,
      cashMovement: parsed.operatingCashFlow! + parsed.investingCashFlow! + parsed.financingCashFlow!,
    };
  }, [parsed, valid]);

  return (
    <section className={styles.card} aria-labelledby="statement-explorer-title">
      <div className={styles.header}>
        <div>
          <span className={styles.eyebrow}>FINANCIAL STATEMENTS · INTERACTIVE EXPLORER</span>
          <h2 id="statement-explorer-title">Connect the three statements</h2>
          <p>Change the hypothetical figures and see how operating performance, short-term financial position and cash movements tell different stories.</p>
        </div>
        <span className={styles.demo}>ILLUSTRATIVE DATA</span>
      </div>
      <div className={styles.disclosure}>All starting figures are fictional teaching values, not data from an MSE-listed company. This simplified exercise is not a complete set of financial statements.</div>
      <div className={styles.layout}>
        <div className={styles.inputs}>
          {(["Income statement", "Financial position", "Cash flow"] as const).map((group) => (
            <fieldset className={styles.group} key={group}>
              <legend>{group}</legend>
              {fields.filter((field) => field.group === group).map((field) => (
                <label className={styles.field} key={field.key}>
                  <span>{field.label}</span>
                  <input
                    type="number"
                    inputMode="decimal"
                    value={values[field.key]}
                    onChange={(event) => setValues((current) => ({ ...current, [field.key]: event.target.value }))}
                    aria-label={field.label}
                  />
                  <small>{field.help}</small>
                </label>
              ))}
            </fieldset>
          ))}
          <button className={styles.reset} type="button" onClick={() => setValues(initial)}>Reset illustrative figures</button>
        </div>
        <div className={styles.results} aria-live="polite">
          {!valid || !metrics ? (
            <div className={styles.warning}>Enter finite values for every field. Blank or invalid inputs are not treated as zero.</div>
          ) : (
            <>
              <div className={styles.result}>
                <small>SIMPLIFIED OPERATING SURPLUS</small>
                <strong>{money(metrics.illustrativeOperatingSurplus)}</strong>
                <span>Revenue less the operating costs entered above; not necessarily reported operating profit.</span>
              </div>
              <div className={styles.result}>
                <small>SIMPLIFIED OPERATING MARGIN</small>
                <strong>{metrics.operatingMargin === null ? "Unavailable" : `${(metrics.operatingMargin * 100).toFixed(1)}%`}</strong>
                <span>Withheld when revenue is not positive.</span>
              </div>
              <div className={styles.result}>
                <small>WORKING CAPITAL</small>
                <strong>{money(metrics.workingCapital)}</strong>
                <span>Current assets minus current liabilities; a snapshot, not a cash balance.</span>
              </div>
              <div className={styles.result}>
                <small>NET CASH MOVEMENT</small>
                <strong>{money(metrics.cashMovement)}</strong>
                <span>Operating + investing + financing cash flows for this simplified example.</span>
              </div>
              <div className={styles.insight}>A business can show a positive operating surplus while cash movement is negative — for example, when it invests heavily or repays financing. Read all three statements together.</div>
            </>
          )}
        </div>
      </div>
    </section>
  );
}
